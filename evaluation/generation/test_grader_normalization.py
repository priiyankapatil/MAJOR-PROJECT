"""
test_grader_normalization.py
Unit tests for verified evaluator normalization logic.
Explicitly verifies:
- Unicode vs ASCII hyphens (e.g. CO‑51 vs CO-51)
- Common pest names and standard acronyms (e.g. Stem‑and‑Root Borer vs Stem and Root Borer vs CSRB)
- SI metric unit notation (e.g. 200 L vs 200 litres vs 200 liters)
- Harmless whitespace and punctuation normalization
- True negative preservation (ensures unexpressed facts remain unsatisfied)
"""

import unittest
import re
import os
import sys

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from evaluation.generation.run_generation_benchmark import (
    normalize_text_for_grading,
    check_fact_satisfaction,
    FACT_PATTERNS_V1,
    FACT_PATTERNS_V2
)

class TestGraderNormalization(unittest.TestCase):

    def test_unicode_hyphen_normalization(self):
        """Test that Unicode non-breaking hyphens, en-dashes, and em-dashes are normalized to ASCII hyphens."""
        # \u2011 is non-breaking hyphen commonly generated by LLMs
        raw_text = "Varieties include CO\u201151, CO\u201147, and ADT\u201147."
        normalized = normalize_text_for_grading(raw_text)
        self.assertIn("CO-51", normalized)
        self.assertIn("CO-47", normalized)
        self.assertIn("ADT-47", normalized)

        # En-dash and em-dash
        dash_text = "Spacing 10\u201315 cm or 20\u201425 cm"
        self.assertEqual(normalize_text_for_grading(dash_text), "Spacing 10-15 cm or 20-25 cm")

    def test_q18_cultivars_matching(self):
        """Test Q18 Fact 0 matching across Unicode hyphens, ASCII hyphens, and whitespace."""
        fact_str = "Biofortification rice cultivars: CO51, CO47, ADT 47, and ADT 37"

        # Model output containing Unicode hyphens
        unicode_ans = "Grow the zinc-efficient rice cultivars **CO\u201151, CO\u201147, ADT\u201147 and ADT\u201137**."
        sat_v2, note_v2 = check_fact_satisfaction(0, "Q18", unicode_ans, fact_str, version="v2")
        self.assertTrue(sat_v2, f"Expected Q18 Fact 0 to match Unicode hyphens in V2, got: {note_v2}")

        # Model output containing standard ASCII hyphens
        ascii_ans = "Grow the zinc-efficient rice cultivars **CO-51, CO-47, ADT-47 and ADT-37**."
        sat_v2_ascii, _ = check_fact_satisfaction(0, "Q18", ascii_ans, fact_str, version="v2")
        self.assertTrue(sat_v2_ascii)

        # Confirm V1 failed on Unicode hyphens
        sat_v1, _ = check_fact_satisfaction(0, "Q18", unicode_ans, fact_str, version="v1")
        self.assertFalse(sat_v1, "V1 should fail on Unicode hyphens")

    def test_q24_stem_and_root_borer_matching(self):
        """Test Q24 Fact 0 matching for common pest name with hyphens and CSRB acronym."""
        fact_str = "Pest identification: Cashew Stem and Root Borer (Plocaederus ferrugineus)"

        # Model output with Unicode hyphens + CSRB acronym
        ans_with_acronym = "DIAGNOSIS: **Cashew Stem\u2011and\u2011Root Borer (CSRB)** – confidence ≈ 92 %"
        sat_v2, note_v2 = check_fact_satisfaction(0, "Q24", ans_with_acronym, fact_str, version="v2")
        self.assertTrue(sat_v2, f"Expected Q24 Fact 0 to match in V2, got: {note_v2}")

        # Model output with plain ASCII name
        ans_ascii = "The pest is Cashew Stem-and-Root Borer attacking the lower trunk."
        sat_v2_ascii, _ = check_fact_satisfaction(0, "Q24", ans_ascii, fact_str, version="v2")
        self.assertTrue(sat_v2_ascii)

        # Confirm V1 failed due to hyphenation and lack of acronym support
        sat_v1, _ = check_fact_satisfaction(0, "Q24", ans_with_acronym, fact_str, version="v1")
        self.assertFalse(sat_v1, "V1 should fail on hyphenated Stem-and-Root Borer")

    def test_q29_si_unit_matching(self):
        """Test Q29 Fact 1 matching for 200 L, 200 litres, 200 liters, and 200lit."""
        fact_str = "Water volume: 200 litres of water (yielding a 0.5% zinc sulphate solution)"

        # Model output with '200 L' (with space)
        ans_200_l = "Add water – pour 200 L of lukewarm water into the drum."
        sat_v2, note_v2 = check_fact_satisfaction(1, "Q29", ans_200_l, fact_str, version="v2")
        self.assertTrue(sat_v2, f"Expected Q29 Fact 1 to match '200 L' in V2, got: {note_v2}")

        # Model output with '200 litres'
        ans_200_litres = "Dissolve in 200 litres of clean water per acre."
        sat_v2_litres, _ = check_fact_satisfaction(1, "Q29", ans_200_litres, fact_str, version="v2")
        self.assertTrue(sat_v2_litres)

        # Model output with '200 liters' (US spelling)
        ans_200_liters = "Mix into 200 liters of water."
        sat_v2_liters, _ = check_fact_satisfaction(1, "Q29", ans_200_liters, fact_str, version="v2")
        self.assertTrue(sat_v2_liters)

        # Confirm V1 failed on '200 L' with whitespace
        sat_v1, _ = check_fact_satisfaction(1, "Q29", ans_200_l, fact_str, version="v1")
        self.assertFalse(sat_v1, "V1 should fail on '200 L' with space")

    def test_q25_true_negative_preservation(self):
        """Ensure Q25 Fact 1 remains unsatisfied when length variability is omitted."""
        fact_str = "Constructed on leveled ground; length can vary based on space"
        truncated_ans = "Vermicompost beds should be built on a leveled, pucca floor to prevent seepage. Typical dimensions: **6 ft (≈1.83 m) long × 3 ft (≈0.91 m) wide ×"

        sat_v2, _ = check_fact_satisfaction(1, "Q25", truncated_ans, fact_str, version="v2")
        self.assertFalse(sat_v2, "Q25 Fact 1 must remain unsatisfied because length variability was omitted")

    def test_q27_true_negative_preservation(self):
        """Ensure Q27 Fact 4 remains unsatisfied when afternoon watering precaution is omitted."""
        fact_str = "Damping-off prevention: avoid excess moisture and avoid afternoon watering"
        omitted_ans = "- Leaving seedlings on the bench for a long time -> they dry out or become stressed, increasing susceptibility to damping-off."

        sat_v2, _ = check_fact_satisfaction(4, "Q27", omitted_ans, fact_str, version="v2")
        self.assertFalse(sat_v2, "Q27 Fact 4 must remain unsatisfied when prevention actions are absent")


if __name__ == "__main__":
    unittest.main()
